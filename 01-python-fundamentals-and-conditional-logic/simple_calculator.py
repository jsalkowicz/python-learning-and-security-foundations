b = int(input("Enter second number: "))

addition = a + b
multiplication = a * b
remainder = a % b
subtraction = a - b
division = a / b

print("Addition is", addition)
print("Multiplication is", multiplication)
print("Remainder is", remainder)
print("Subtraction is", subtraction)
print("Division is", division)
